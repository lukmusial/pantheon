"""Export where each statue's painted eyes are, for the walk-through app's ghost mode, in which the
statues' eyes follow the visitor (ue/Pantheon/Source/Pantheon/F3GhostDriver.cpp, M_Statue).

blender/paint_statues.py paints the eyes from a template (almond opening, iris, pupil) laid in the
plane of a frontal face view and fitted to the eye corners. This script reads what that run cached
(tools/polychromy_cache/<key>/face.json and the face view's camera) and writes, per statue and eye,
the template's frame in the statue's own space: centre between the corners, the unit axis from the
inner to the outer corner, the unit axis up the face, the eye width (m) and the template's vertical
offset (fraction of the width), plus the iris colour from blender/polychromy_palette.json.

Usage: python3 tools/statue_eyes.py     (writes ue/Pantheon/Source/Pantheon/F3StatueEyes.inl)
"""

import glob
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CACHE = os.path.join(ROOT, "tools", "polychromy_cache")
OUT = os.path.join(ROOT, "ue", "Pantheon", "Source", "Pantheon", "F3StatueEyes.inl")


def hex_linear(h):
    h = h.lstrip("#")
    return [(int(h[i:i + 2], 16) / 255.0) ** 2.2 for i in (0, 2, 4)]   # as M_Statue converts the paint


def iris_colour(palette, key):
    spec = palette.get("statues", {}).get(key, {}).get("iris") or palette["default"]["iris"]
    c = spec["color"]
    return hex_linear(c if c.startswith("#") else palette["pigments"][c])


def main():
    palette = json.load(open(os.path.join(ROOT, "blender", "polychromy_palette.json")))
    rows = []
    for path in sorted(glob.glob(os.path.join(ROOT, "assets", "statues", "painted", "*.json"))):
        key = json.load(open(path))["key"]
        fpath = os.path.join(CACHE, key, "face.json")
        if not os.path.exists(fpath):
            print("no cached face for", key)
            continue
        face = json.load(open(fpath))
        if not face.get("found"):
            print("no face found on", key)
            continue
        view = json.load(open(os.path.join(CACHE, key, "views", face["view"] + ".json")))
        V = view["V"]   # world -> camera; camera x is right, y is up in the image
        right, up = V[0][:3], V[1][:3]
        pixel = float(view["view"].get("ortho_scale", 1.0)) / max(view["w"], view["h"])
        eyes = face["geometry"]["eyes"]
        t_iris = sum(e["t_iris"] for e in eyes) / len(eyes)
        t_off = max(-0.08, min(0.08, t_iris)) * 0.5   # as paint_statues.py sets centre_offset
        out = []
        for e, c in zip(eyes, face["eyes3d"]):
            # image y runs down: a pixel direction (x, y) is x * right - y * up in the statue's space
            u = [e["u"][0] * right[k] - e["u"][1] * up[k] for k in range(3)]
            v = [e["up"][0] * right[k] - e["up"][1] * up[k] for k in range(3)]
            out.append((c, u, v, e["width"] * pixel, t_off))
        rows.append((key, out, iris_colour(palette, key)))

    def vec(v):
        return "{%.5f, %.5f, %.5f}" % tuple(v)

    with open(OUT, "w") as fh:
        fh.write("// Generated by tools/statue_eyes.py from the statue painting pipeline's cache. Do not edit.\n")
        fh.write("// key, two eyes {centre (m), inner-to-outer axis, up axis, width (m), vertical offset}, iris colour (linear).\n")
        fh.write("// The statue's own space as in Blender: x right, y back, z up.\n")
        for key, eyes, iris in rows:
            e = ", ".join("{%s, %s, %s, %.5f, %.4f}" % (vec(c), vec(u), vec(v), w, t) for c, u, v, w, t in eyes)
            fh.write('{TEXT("%s"), {%s}, %s},\n' % (key, e, vec(iris)))
    print("wrote %d statues to %s" % (len(rows), OUT))


if __name__ == "__main__":
    main()
